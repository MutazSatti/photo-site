{{--
    يمرّر الصفحة إلى ما بداخله حين يصل الحدث المسمّى في on.

    نماذج اللوحة تُرسم في موضع ثابت والقوائم تطول، فيقع زرّ «تعديل» بعيدًا عن
    النموذج — فوقه أو تحته حسب التخطيط. وبلا تمرير يبدو الضغط بلا أثر، إذ
    يُفتح النموذج خارج مجال النظر.

    والتمرير مشروط بأن يكون خارج النظر فعلًا: نموذج القسم الجانبي لاصق وظاهر
    دائمًا على الشاشات الكبيرة، فتمريره إليه قفزة بلا فائدة. والحدّ 0.6 من
    ارتفاع الشاشة يميّز «ظاهر بما يكفي» من «تحت الطيّة».

    وهو معلّق على الحدث لا على ظهور العنصر: النموذج قد يكون مفتوحًا سلفًا حين
    يُضغط تعديل عنصر آخر، فلا يُعاد إنشاؤه ولا يكفي x-init.
--}}
